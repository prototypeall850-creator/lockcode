// Colored ANSI lines (for CLI output / epilogue).
export function artAnsi(pad = ""): string[] {
  return artSegments.map((segs) => pad + segs.map(([sgr, text]) => `\x1b[${sgr}m${text}`).join("") + "\x1b[0m")
}
